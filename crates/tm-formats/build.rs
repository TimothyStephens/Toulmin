//! Item 25. Generates, from `src/catalog.rs`:
//!
//! * `$OUT_DIR/codes.rs`: the `Code` enum, one variant per catalog entry;
//! * `$OUT_DIR/errors.md`: the text of `docs/errors.md`, one row per code
//!   with its gate as a column, also written to `$TM_ERRORS_OUT` when that
//!   variable is set, which is what `scripts/ci/spec-drift.sh` compares
//!   with the committed `docs/errors.md`.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "a build script reports failure by panicking"
)]

use std::fmt::Write as _;
use std::path::PathBuf;

include!("src/catalog.rs");

fn library(code: &str) -> &'static str {
    match code.as_bytes().get(1) {
        Some(b'1') => "formats",
        Some(b'2') => "record",
        Some(b'3') => "files",
        Some(b'4') => "runs",
        Some(b'5') => "checker",
        Some(b'6') => "claims",
        Some(b'7') => "core and permissions",
        Some(b'8') => "front ends",
        _ => panic!("catalog code {code} has no library digit"),
    }
}

fn markdown() -> String {
    let mut md = String::new();
    md.push_str("# Error catalog\n\n");
    md.push_str(
        "Generated by `crates/tm-formats/build.rs` from `crates/tm-formats/src/catalog.rs` \
         (design 11.12, items 20, 25, and 94). Do not edit by hand: \
         `scripts/ci/spec-drift.sh` fails when this file differs from the generator's output.\n\n",
    );
    md.push_str(
        "Codes are stable; messages may change. `Gate` is the earliest gate at which the code \
         can be produced. Each error carries `code`, `message`, `rule`, `field` (a JSON \
         Pointer, RFC 6901, or `null`), `owner_command`, and `subject`.\n\n",
    );
    md.push_str("| Code | Library | Gate | Message |\n| --- | --- | --- | --- |\n");
    for (code, gate, message) in CATALOG {
        writeln!(md, "| `{code}` | {} | {gate} | {message} |", library(code)).unwrap();
    }
    md
}

fn codes_rs() -> String {
    let mut s = String::new();
    s.push_str("/// A stable catalog code (design 11.12), generated from `src/catalog.rs`.\n");
    s.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n");
    s.push_str("pub enum Code {\n");
    for (code, gate, message) in CATALOG {
        writeln!(s, "    /// {message} (gate {gate}).\n    {code},").unwrap();
    }
    s.push_str(
        "}\n\nimpl Code {\n    /// Every code, in catalog order.\n    pub const ALL: &[Code] = &[",
    );
    for (code, _, _) in CATALOG {
        write!(s, "Code::{code}, ").unwrap();
    }
    s.push_str("];\n\n    /// The catalog index of this code.\n    #[must_use]\n    pub fn index(self) -> usize {\n        match self {\n");
    for (i, (code, _, _)) in CATALOG.iter().enumerate() {
        writeln!(s, "            Code::{code} => {i},").unwrap();
    }
    s.push_str("        }\n    }\n}\n");
    s
}

fn main() {
    println!("cargo::rerun-if-changed=src/catalog.rs");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-env-changed=TM_ERRORS_OUT");
    let mut seen = std::collections::BTreeSet::new();
    for (code, gate, _) in CATALOG {
        assert!(seen.insert(*code), "duplicate catalog code {code}");
        assert!(matches!(gate, 'A' | 'B' | 'C' | 'D'), "bad gate for {code}");
    }
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("codes.rs"), codes_rs()).expect("write codes.rs");
    let md = markdown();
    std::fs::write(out.join("errors.md"), &md).expect("write errors.md");
    if let Some(path) = std::env::var_os("TM_ERRORS_OUT") {
        std::fs::write(path, &md).expect("write TM_ERRORS_OUT");
    }
}
